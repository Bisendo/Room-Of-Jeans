// Helper function to format price in TZS
export const formatPrice = (price) => {
  return new Intl.NumberFormat('sw-TZ', {
    style: 'currency',
    currency: 'TZS',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0
  }).format(price);
};

// Helper function to get products by category
export const getProductsByCategory = (category) => {
  return products.filter(product => product.category === category);
};

// Helper function to get product by id
export const getProductById = (id) => {
  return products.find(product => product.id === parseInt(id));
};

// Helper function to get featured products
export const getFeaturedProducts = () => {
  return products.filter(product => product.discount >= 30);
};

// Helper function to get new arrivals (last 4 products)
export const getNewArrivals = () => {
  return products.slice(-4);
};

// Helper function to get top rated products
export const getTopRatedProducts = () => {
  return [...products].sort((a, b) => b.rating - a.rating).slice(0, 4);
};

// Helper function to get products on sale
export const getProductsOnSale = () => {
  return products.filter(product => product.discount && product.discount > 0);
};

